CREATE TABLE cliente (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento VARCHAR2(11) NOT NULL UNIQUE,
  nombres VARCHAR2(120) NOT NULL,
  telefono VARCHAR2(15)
);
CREATE TABLE servicio (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR2(7) NOT NULL UNIQUE,
  nombre VARCHAR2(80) NOT NULL,
  precio NUMBER(10,2) NOT NULL,
  duracion_min NUMBER(4) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT ck_servicio_precio CHECK (precio > 0)
);
CREATE TABLE vehiculo (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR2(7) NOT NULL UNIQUE,
  marca VARCHAR2(40) NOT NULL,
  modelo VARCHAR2(40) NOT NULL,
  anio NUMBER(4) NOT NULL,
  cliente_id NUMBER NOT NULL REFERENCES cliente(id)
);
CREATE TABLE orden_servicio (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(9) NOT NULL UNIQUE,
  fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  vehiculo_id NUMBER NOT NULL REFERENCES vehiculo(id),
  kilometraje NUMBER(7) NOT NULL,
  estado VARCHAR2(12) NOT NULL,
  total NUMBER(10,2) NOT NULL,
  usuario_registro VARCHAR2(30) NOT NULL,
  motivo_anulacion VARCHAR2(200)
);
CREATE TABLE detalle_orden (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id NUMBER NOT NULL REFERENCES orden_servicio(id),
  servicio_id NUMBER NOT NULL REFERENCES servicio(id),
  cantidad NUMBER(2) NOT NULL,
  precio_unitario NUMBER(10,2) NOT NULL,
  subtotal NUMBER(10,2) NOT NULL
);
CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(60) NOT NULL UNIQUE,
  password VARCHAR2(100) NOT NULL,
  nombrecompleto VARCHAR2(120) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT ck_usuario_activo CHECK (activo IN (0,1))
);
CREATE TABLE roles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(40) NOT NULL UNIQUE
);
CREATE TABLE usuario_roles (
  usuario_id NUMBER NOT NULL REFERENCES usuarios(id),
  rol_id NUMBER NOT NULL REFERENCES roles(id),
  CONSTRAINT pk_usuario_roles PRIMARY KEY (usuario_id, rol_id)
);
CREATE SEQUENCE seq_numero_orden START WITH 5 INCREMENT BY 1 NOCACHE;

